<p>Pour être éligible à la certification en tant qu'étudiant EVC, l'étudiant doit remplir l'ensemble des cinq (05) critères ci-dessous :</p>
<ul>
    <li><strong>1. Avoir soldé sa formation :</strong> l'étudiant doit avoir réglé intégralement les frais de sa formation avant toute demande de certification.</li>
    <li><strong>2. Être à jour dans ses travaux :</strong> tous les travaux pratiques, devoirs et évaluations requis doivent être réalisés et validés.</li>
    <li><strong>3. Participer aux activités et formations EVC :</strong> l'étudiant doit prendre part activement aux activités, ateliers et sessions de formation organisées par l'EVC.</li>
    <li><strong>4. Soumettre un rapport de fin de formation :</strong> un rapport de fin de formation complet et conforme aux modalités EVC doit être déposé.</li>
    <li><strong>5. Avoir participé à au moins un Studio Créatif :</strong> la participation à un minimum d'un Studio Créatif est obligatoire pour prétendre à la certification.</li>
</ul>

<h3>Session de rattrapage</h3>
<p>En cas de non-éligibilité, l'EVC offre à l'étudiant une session de rattrapage d'une durée de <strong>1 semaine et 3 jours</strong>, offerte à hauteur de <strong>35 000 FCFA</strong>.</p>
<p>Si, à l'issue de cette session de rattrapage, l'étudiant n'est toujours pas éligible, il sera basculé vers un <strong>profil normal</strong> et devra effectuer une nouvelle inscription pour reprendre le processus.</p>

<h3>Pénalité de retard de solde</h3>
<p>Le règlement du solde de la formation est obligatoire. Tout retard dans le paiement du solde expose l'étudiant à une pénalité de <strong>5 350 FCFA</strong>.</p>

<h3>Réalisation et soumission des projets</h3>
<p>Chaque étudiant reçoit des projets depuis son espace étudiant. Il doit réaliser ces projets dans les délais impartis et les soumettre dans la classe virtuelle.</p>
